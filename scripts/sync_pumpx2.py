#!/usr/bin/env python3
"""Regenerate data.js from pumpX2's notification enums.

    scripts/sync_pumpx2.py ../pumpX2 --ref origin/dev
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

CURRENT_STATUS = "messages/src/main/java/com/jwoglom/pumpx2/pump/messages/response/currentStatus"

# (key, source file, enum, pumpX2's isKnown rule)
CATEGORIES = [
    ("MALFUNCTION", "MalfunctionBitmaskStatusResponse", "MalfunctionType", "all"),
    ("ALARM", "AlarmStatusResponse", "AlarmResponseType", "description"),
    ("ALERT", "AlertStatusResponse", "AlertResponseType", "description"),
    ("CGM_ALERT", "CGMAlertStatusResponse", "CGMAlert", "not_default"),
    ("REMINDER", "ReminderStatusResponse", "ReminderType", "not_default"),
]

ENTRY = re.compile(
    r'(?:/\*\*\s*Tandem firmware name:\s*(\S+)\s*\*/\s*)?'
    r'\b([A-Z][A-Z0-9_]*)\((\d+)((?:\s*,\s*(?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+)?)\)'
)
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def read(repo, ref, path):
    if ref:
        return subprocess.run(
            ["git", "-C", repo, "show", f"{ref}:{path}"],
            check=True, capture_output=True, text=True,
        ).stdout
    return (Path(repo) / path).read_text()


def enum_body(source, enum):
    start = source.index(f"enum {enum} ")
    body = source[source.index("{", start) + 1:]
    return body[:re.search(r"^\s*;\s*$", body, re.M).start()]


def entries(source, enum, rule):
    out = []
    for firmware, name, ident, rest in ENTRY.findall(enum_body(source, enum)):
        desc = "".join(STRING.findall(rest)) or None
        if firmware.startswith("NUM_"):  # the enum's count, not an entry
            firmware = ""
        known = {
            "all": True,
            "description": bool(desc and desc.strip()),
            "not_default": not name.startswith("DEFAULT_"),
        }[rule]
        out.append({"id": int(ident), "name": name, "firmware": firmware or None,
                    "desc": desc, "known": known})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pumpx2")
    ap.add_argument("--ref", help="read from this git ref instead of the working tree")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "data.js"))
    args = ap.parse_args()

    commit = subprocess.run(
        ["git", "-C", args.pumpx2, "rev-parse", "--short", args.ref or "HEAD"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()

    tables = {}
    for key, cls, enum, rule in CATEGORIES:
        tables[key] = entries(read(args.pumpx2, args.ref, f"{CURRENT_STATUS}/{cls}.java"), enum, rule)

    highest_aam = read(args.pumpx2, args.ref, f"{CURRENT_STATUS}/HighestAamResponse.java")
    ignorable_block = highest_aam[highest_aam.index("IGNORABLE_CODES"):]
    ignorable_block = ignorable_block[:ignorable_block.index("};")]
    ignorable = [[int(a), int(b)] for a, b in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", ignorable_block)]

    lines = [
        "// Generated by scripts/sync_pumpx2.py; do not edit by hand.",
        "var PUMPX2 = {",
        f"  source: {json.dumps((args.ref or 'HEAD').removeprefix('origin/') + ' @ ' + commit)},",
        f"  ignorableCodes: {json.dumps(ignorable)},",
    ]
    for key, rows in tables.items():
        lines.append(f"  {key}: [")
        lines += [f"    {json.dumps(row, ensure_ascii=False)}," for row in rows]
        lines.append("  ],")
    lines += ["};", "", 'if (typeof module !== "undefined") module.exports = PUMPX2;', ""]
    Path(args.out).write_text("\n".join(lines))


if __name__ == "__main__":
    main()
